create table if not exists public.users (
  id text primary key,
  role text not null check (role in ('client', 'admin')),
  name text not null,
  company text not null default '',
  email text not null unique,
  phone text not null default '',
  password text not null,
  is_approved boolean not null default true,
  status text not null default 'Approved',
  created_at timestamptz not null default now()
);

-- Supabase Auth profiles for client accounts created by auth.signUp().
-- The profile ID is the Auth user's UUID, not the legacy public.users text ID.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text,
  phone text not null default '',
  company text not null default '',
  role text not null default 'client' check (role in ('client', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Backfill columns for an existing profiles table without changing existing data.
alter table public.profiles
  add column if not exists id uuid references auth.users(id) on delete cascade,
  add column if not exists name text not null default '',
  add column if not exists email text,
  add column if not exists phone text not null default '',
  add column if not exists company text not null default '',
  add column if not exists role text not null default 'client',
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

-- The trigger's ON CONFLICT target must be unique even if the table pre-existed.
create unique index if not exists profiles_id_uidx on public.profiles (id);

alter table public.profiles enable row level security;
grant select, insert on public.profiles to authenticated;
grant all on public.profiles to service_role;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles
  for insert
  to authenticated
  with check ((select auth.uid()) = id);

